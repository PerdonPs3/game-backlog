CREATE TABLE games (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL CHECK (length(trim(title)) BETWEEN 1 AND 200),
    platform TEXT NOT NULL CHECK (length(trim(platform)) BETWEEN 1 AND 80),
    status TEXT NOT NULL DEFAULT 'Backlog'
        CHECK (status IN ('Backlog', 'Playing', 'Completed', 'On hold', 'Dropped')),
    rating SMALLINT CHECK (rating BETWEEN 1 AND 10),
    review TEXT NOT NULL DEFAULT '' CHECK (length(review) <= 2000),
    igdb_id BIGINT CHECK (igdb_id > 0),
    cover_image_id TEXT,
    started_on DATE,
    completed_on DATE,
    is_favorite SMALLINT NOT NULL DEFAULT 0 CHECK (is_favorite IN (0, 1)),
    is_goty SMALLINT NOT NULL DEFAULT 0 CHECK (is_goty IN (0, 1)),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CHECK (started_on IS NULL OR completed_on IS NULL OR completed_on >= started_on)
);
CREATE TABLE game_lists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 80),
    name_key TEXT NOT NULL UNIQUE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);
CREATE TABLE game_list_members (
    list_id BIGINT NOT NULL REFERENCES game_lists(id) ON DELETE CASCADE,
    game_id BIGINT NOT NULL REFERENCES games(id) ON DELETE CASCADE,
    PRIMARY KEY (list_id, game_id)
);
CREATE INDEX list_members_by_game ON game_list_members(game_id);
CREATE INDEX games_catalog_platform ON games(igdb_id, lower(trim(platform)));
ALTER TABLE games ENABLE ROW LEVEL SECURITY;
ALTER TABLE game_lists ENABLE ROW LEVEL SECURITY;
ALTER TABLE game_list_members ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON games, game_lists, game_list_members FROM PUBLIC;
